#!/usr/bin/env python3
"""Build the UGC NET PYQ bank (js/ugc-bank.js) from per-paper data in pyq/ugc/.

A paper id looks like 2025-06-p2 (session year-month, paper 1 or 2). Per paper:
  pyq/ugc/data/<paper>-map.tsv   n <TAB> unit:topic          (unit ids from js/ugc-syllabus.js)
  pyq/ugc/keys/<paper>.json      [{n, key: "A".."D", src: "nta" | "pw" | "solved"}, …]
  pyq/ugc/img/ugc-<paper>-<n>.webp   cropped question images (tools/crop_two_column.py)
  pyq/ugc/data/<paper>.json      questions, written by `add`

Usage:
  python3 tools/build_ugc_bank.py add 2025-06-p2 "June 2025" meta.json
  python3 tools/build_ugc_bank.py build
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "pyq" / "ugc" / "data"


def units():
    src = (ROOT / "js" / "ugc-syllabus.js").read_text()
    out = {}
    for m in re.finditer(r'id: "(p\du\d+)".*?topics: \[(.*?)\] \}', src):
        out[m.group(1)] = len(re.findall(r'"[^"]*"', m.group(2)))
    return out


def add(paper, session, meta_path):
    U = units()
    meta = {int(n): v for n, v in json.load(open(meta_path)).items()}
    key = {r["n"]: r for r in json.load(open(ROOT / "pyq" / "ugc" / "keys" / f"{paper}.json"))}
    mapping = {}
    for line in (DATA / f"{paper}-map.tsv").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        n, loc = line.split("\t")[:2]
        u, t = loc.strip().split(":")
        if u not in U or not 0 <= int(t) < U[u]:
            raise SystemExit(f"Q{n}: bad unit/topic {loc}")
        mapping[int(n)] = (u, int(t))
    missing = sorted(set(meta) - set(mapping)) + sorted(set(meta) - set(key))
    if missing:
        raise SystemExit(f"unmapped / unkeyed questions: {missing}")
    paper_no = int(paper.rsplit("-p", 1)[1])
    out = []
    for n in sorted(meta):
        img = ROOT / "pyq" / "ugc" / "img" / f"ugc-{paper}-{n}.webp"
        if not img.exists():
            raise SystemExit(f"missing image {img}")
        if key[n]["key"] not in "ABCD" or len(key[n]["key"]) != 1:
            raise SystemExit(f"Q{n}: bad key {key[n]['key']!r}")
        u, t = mapping[n]
        text = re.sub(r"^Q\d+\.?\s*", "", meta[n]["text"]).strip()
        out.append({"id": f"ugc-{paper}-{n}", "xp": f"ugc-{paper}", "s": session, "p": paper_no, "n": n, "u": u, "t": t,
                    "img": f"pyq/ugc/img/ugc-{paper}-{n}.webp", "q": text[:1500], "ans": key[n]["key"], "ks": key[n].get("src", "nta")})
    (DATA / f"{paper}.json").write_text(json.dumps(out, ensure_ascii=False, indent=1))
    print(f"{paper}: {len(out)} questions")


def build():
    qs, papers = [], {}
    for f in sorted(DATA.glob("*-p[12].json")):
        year_qs = json.loads(f.read_text())
        qs += year_qs
        papers[f.stem] = {"questions": len(year_qs), "session": year_qs[0]["s"] if year_qs else ""}
    body = ",\n".join("  " + json.dumps(q, ensure_ascii=False, separators=(",", ":")) for q in qs)
    js = ("/* UGC NET PYQ bank — generated by tools/build_ugc_bank.py (edit pyq/ugc/, not this file).\n"
          "   q: {id, xp (explanation file), s (session), p (paper 1|2), n, u (unit id), t (topic index), img, q (text), ans (A-D),\n"
          "       ks (key source: nta = official NTA final key, pw = Physics Wallah key, solved = worked out by hand)} */\n"
          f"const UGC_BANK = {{\n papers: {json.dumps(papers)},\n q: [\n{body}\n ],\n}};\n")
    (ROOT / "js" / "ugc-bank.js").write_text(js)
    print(f"js/ugc-bank.js: {len(qs)} questions from {', '.join(papers)}")


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "build":
        build()
    elif len(sys.argv) == 5 and sys.argv[1] == "add":
        add(sys.argv[2], sys.argv[3], sys.argv[4])
    else:
        print(__doc__)
        sys.exit(1)
