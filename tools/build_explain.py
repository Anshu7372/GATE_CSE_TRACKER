#!/usr/bin/env python3
"""Build js/explain/<paper>.js from pyq/explain/<paper>.md (hint, concept, tips, solution, references, syllabus tag).

Source format (one block per question, n = question number in the paper):

    @@ 12
    syl: in                          # in | partial | out, optionally followed by " | reason"
    == hint
    What to remember to crack it (short).
    == concept
    Concept from the basics (markdown-lite: **bold**, `code`, - lists, 1. lists, ### heading, ``` blocks).
    == tips
    Tricks / traps.
    == sol
    Step-by-step solution ending with the answer.
    == refs
    - Book, chapter / lecture / GATE Overflow pointer

Usage:
  python3 tools/build_explain.py            # build every pyq/explain/*.md
  python3 tools/build_explain.py 2026-1     # build one paper
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "pyq" / "explain"
OUT = ROOT / "js" / "explain"
SECTIONS = ("hint", "concept", "tips", "sol", "refs")


def parse(path):
    qs, cur, sec = {}, None, None
    for ln, line in enumerate(path.read_text().split("\n"), 1):
        m = re.match(r"^@@\s*(\d{1,2})\s*$", line)
        if m:
            cur = {"n": int(m.group(1))}
            if cur["n"] in qs:
                raise SystemExit(f"{path.name}:{ln}: duplicate question {cur['n']}")
            qs[cur["n"]] = cur
            sec = None
            continue
        if cur is None:
            continue
        m = re.match(r"^syl:\s*(in|partial|out)\s*(?:\|\s*(.*))?$", line)
        if m and sec is None:
            cur["syl"] = {"s": m.group(1), "why": (m.group(2) or "").strip()}
            continue
        m = re.match(r"^==\s*(\w+)\s*$", line)
        if m:
            sec = m.group(1)
            if sec not in SECTIONS:
                raise SystemExit(f"{path.name}:{ln}: unknown section {sec!r}")
            cur[sec] = []
            continue
        if sec:
            cur[sec].append(line)
    return qs


def build(paper):
    path = SRC / f"{paper}.md"
    bank = {q["n"]: q for q in json.loads((ROOT / "pyq" / "data" / f"{paper}.json").read_text())}
    qs = parse(path)
    out, problems = {}, []
    for n in sorted(bank):
        x = qs.get(n)
        if not x:
            continue
        for s in SECTIONS:
            if not "\n".join(x.get(s, [])).strip():
                problems.append(f"Q{n}: empty '{s}'")
        if "syl" not in x:
            problems.append(f"Q{n}: missing 'syl:' line")
        if x.get("syl", {}).get("s") in ("partial", "out") and not x["syl"]["why"]:
            problems.append(f"Q{n}: syllabus '{x['syl']['s']}' needs a reason")
        out[bank[n]["id"]] = {
            "syl": x.get("syl", {"s": "in", "why": ""}),
            **{s: "\n".join(x.get(s, [])).strip() for s in SECTIONS},
        }
    extra = sorted(set(qs) - set(bank))
    if extra:
        problems.append(f"questions not in the bank: {extra}")
    if problems:
        raise SystemExit(f"{paper}: " + "; ".join(problems))
    OUT.mkdir(parents=True, exist_ok=True)
    body = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
    (OUT / f"{paper}.js").write_text(
        f"/* Generated by tools/build_explain.py from pyq/explain/{paper}.md — edit the .md, not this file. */\n"
        f"Object.assign((window.PYQ_EXPLAIN = window.PYQ_EXPLAIN || {{}}), {body});\n")
    missing = sorted(set(bank) - set(qs))
    print(f"{paper}: {len(out)}/{len(bank)} questions explained" + (f" (missing {missing})" if missing else ""))


if __name__ == "__main__":
    papers = sys.argv[1:] or sorted(p.stem for p in SRC.glob("*.md"))
    for p in papers:
        build(p)
